def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    R = 6371.0
    dlat = radians(lat2 - lat1)
    dlon = radians(lon2 - lon1)
    a = sin(dlat / 2) ** 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon / 2) ** 2
    return R * 2 * asin(sqrt(a))


def geocode(postal_code: str) -> tuple[float, float] | None:
    """Converte postal code canadense em (lat, lon)."""
    clean = postal_code.upper().replace(" ", "")
    # Exact match
    if clean in MONTREAL_COORDS:
        return MONTREAL_COORDS[clean]
    # FSA match (first 3 chars)
    fsa = clean[:3]
    if fsa in MONTREAL_COORDS:
        return MONTREAL_COORDS[fsa]
    return None


def is_within_radius(lat: float, lon: float) -> bool:
    return haversine_km(CENTER_LAT, CENTER_LON, lat, lon) <= RADIUS_KM


def distance_from_center(lat: float, lon: float) -> float:
    return haversine_km(CENTER_LAT, CENTER_LON, lat, lon)
